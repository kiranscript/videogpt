import type { TimelineEvent, VideoProject } from "@/lib/rendering";

export function createReplicationProject(): VideoProject {
  const events: TimelineEvent[] = [
    {
      id: "bg",
      type: "background",
      start: 0,
      end: 10,
      layer: 0,
      background: {
        kind: "gradient",
        from: "#071b21",
        to: "#101727",
        angle: 135,
      },
    },
    {
      id: "title",
      type: "text",
      start: 0,
      end: 10,
      layer: 5,
      text: "One write. Two replicas.",
      x: 140,
      y: 130,
      maxWidth: 1640,
      fontSize: 76,
      fontWeight: 800,
      color: "#ecfeff",
      opacity: { from: 0, to: 1, easing: "easeOut" },
    },
    {
      id: "subtitle",
      type: "text",
      start: 0,
      end: 10,
      layer: 5,
      text: "Follow a database update as it travels through the system.",
      x: 140,
      y: 245,
      maxWidth: 1600,
      fontSize: 32,
      color: "#9dbcc6",
    },
  ];
  for (const [index, x] of [340, 960, 1580].entries()) {
    events.push(
      {
        id: `node-${index}`,
        type: "shape",
        shapeType: "rect",
        x: x - 180,
        y: 430,
        width: 360,
        height: 260,
        radius: 30,
        fill: "#132d37",
        stroke: index === 0 ? "#5eead4" : "#548694",
        strokeWidth: 3,
        start: 0,
        end: 10,
        layer: 2,
      },
      {
        id: `icon-${index}`,
        type: "shape",
        shapeType: "icon",
        iconName: "database",
        cx: x,
        cy: 520,
        size: 92,
        color: "#5eead4",
        start: 0,
        end: 10,
        layer: 3,
      },
      {
        id: `label-${index}`,
        type: "text",
        text: index === 0 ? "Primary" : `Replica ${index}`,
        x,
        y: 615,
        maxWidth: 330,
        fontSize: 36,
        align: "center",
        color: "#e2f5f7",
        start: 0,
        end: 10,
        layer: 4,
      },
    );
  }
  for (const [index, x] of [560, 1180].entries()) {
    events.push(
      {
        id: `arrow-${index}`,
        type: "shape",
        shapeType: "line",
        x1: x,
        y1: 560,
        x2: x + 180,
        y2: 560,
        stroke: "#5eead4",
        lineWidth: 6,
        arrowEnd: true,
        start: 1 + index * 3,
        end: 10,
        layer: 3,
      },
      {
        id: `packet-${index}`,
        type: "shape",
        shapeType: "circle",
        x,
        y: 560,
        radius: 12,
        fill: "#fbbf24",
        start: 1 + index * 3,
        end: 4 + index * 3,
        layer: 4,
        translateX: { from: 0, to: 180, easing: "linear" },
      },
    );
  }
  events.push({
    id: "caption",
    type: "text",
    text: "Replication takes time. Until updates arrive, replicas may serve older data.",
    x: 960,
    y: 850,
    maxWidth: 1600,
    fontSize: 36,
    align: "center",
    color: "#9dbcc6",
    start: 3,
    end: 10,
    layer: 5,
  });
  return {
    id: "demo-replication",
    name: "Database replication",
    width: 1920,
    height: 1080,
    duration: 10,
    events,
    chapters: [
      { name: "The primary", time: 0 },
      { name: "First replica", time: 1 },
      { name: "Replication lag", time: 4 },
      { name: "Catch up", time: 7 },
    ],
  };
}
